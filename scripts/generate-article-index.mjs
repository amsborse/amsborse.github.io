/**
 * Rebuilds `src/data/articleIndex.ts` from all `src/content/articles/*.md` files,
 * sorted by frontmatter `date` descending (newest first). Ties break on slug.
 *
 * Run: node scripts/generate-article-index.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const dir = path.join(root, "src", "content", "articles");
const outFile = path.join(root, "src", "data", "articleIndex.ts");

function parseDate(raw) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(raw);
  if (!m) return "0000-00-00";
  const fm = m[1];
  const line = fm.split(/\r?\n/).find((l) => l.startsWith("date:"));
  if (!line) return "0000-00-00";
  const v = line.slice(line.indexOf(":") + 1).trim().replace(/^"|"$/g, "");
  return v || "0000-00-00";
}

function main() {
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".md"));
  const items = files.map((f) => {
    const slug = f.replace(/\.md$/i, "");
    const raw = fs.readFileSync(path.join(dir, f), "utf8");
    return { slug, date: parseDate(raw) };
  });
  items.sort((a, b) => {
    const d = b.date.localeCompare(a.date);
    if (d !== 0) return d;
    return a.slug.localeCompare(b.slug);
  });
  const slugs = items.map((i) => i.slug);

  const lines = [];
  lines.push("/**");
  lines.push(" * Auto-generated by `node scripts/generate-article-index.mjs` (sorted by date desc).");
  lines.push(" * Edit order by re-running the script after adding/removing `.md` files, or adjust manually.");
  lines.push(" */");
  lines.push("");
  lines.push("export const articleOrder = [");
  for (const s of slugs) {
    lines.push(`  ${JSON.stringify(s)},`);
  }
  lines.push("] as const;");
  lines.push("");
  lines.push("export type ArticleSlug = (typeof articleOrder)[number];");
  lines.push("");

  fs.writeFileSync(outFile, lines.join("\n"), "utf8");
  console.log(`Wrote ${slugs.length} slugs to ${path.relative(root, outFile)}`);
}

main();
