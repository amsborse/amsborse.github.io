import type { Orbit, Point, Rect } from "@amsborse/arsenal-scene";

export type PlateName =
  "about" | "experience" | "projects" | "writing" | "learning" | "contact" | "horizon";
export type PlateTheme = "dark" | "light";
export interface Lantern extends Point {
  rx: number;
  ry: number;
  reflection: Point;
  oil?: boolean;
}
export interface LifeMap {
  width: number;
  height: number;
  horizon: number;
  lanterns: readonly Lantern[];
  falls: readonly Rect[];
  rings: readonly (Orbit & { clip?: Rect })[];
  orb?: Point & { r: number };
  ripples: readonly (Point & { radius: number })[];
  /** Solid objects interrupt the lake mask, including the boat and dock. */
  land: readonly (readonly Point[])[];
  mist: readonly Rect[];
  foliage: Rect;
}
const rect = (x0: number, y0: number, x1: number, y1: number): Rect => ({ x0, y0, x1, y1 });
const polygon = (...xy: number[]): Point[] =>
  Array.from({ length: xy.length / 2 }, (_, i) => ({ x: xy[i * 2], y: xy[i * 2 + 1] }));
const lamp = (
  x: number,
  y: number,
  rx: number,
  ry: number,
  reflectionY: number,
  oil = false
): Lantern => ({ x, y, rx, ry, reflection: { x, y: reflectionY }, oil });
const ring = (
  cx: number,
  cy: number,
  a: number,
  b: number,
  rot = 0,
  clip?: Rect
): Orbit & { clip?: Rect } => ({
  cx,
  cy,
  a,
  b,
  rot,
  speed: 0.13,
  ...(clip ? { clip } : {}),
});
const scene = (map: Omit<LifeMap, "width" | "height">, width = 1672): LifeMap => ({
  width,
  height: 941,
  ...map,
});

