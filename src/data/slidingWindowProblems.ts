export type WindowInputKind = "array" | "string" | "matrix";
export type WindowStructureKind = "none" | "frequency" | "deque" | "queue" | "stack";

export type WindowValue = string | number;

export interface WindowVisualStep {
  line: number;
  left: number;
  right: number;
  active: number[];
  entering?: number;
  leaving?: number;
  valid: boolean;
  action: string;
  note: string;
  variables: Record<string, string | number>;
  frequency?: Record<string, number>;
  deque?: WindowValue[];
  queue?: WindowValue[];
  stack?: WindowValue[];
  best?: string | number;
}

export interface SlidingWindowProblem {
  id: string;
  level: number;
  title: string;
  pattern: string;
  goal: string;
  inputKind: WindowInputKind;
  inputLabel: string;
  input: WindowValue[] | WindowValue[][];
  targetLabel?: string;
  targetValue?: string | number;
  structure: WindowStructureKind;
  structureLabel?: string;
  code: string[];
  steps: WindowVisualStep[];
}

const range = (left: number, right: number) =>
  Array.from({ length: Math.max(0, right - left + 1) }, (_, index) => left + index);

const fixedMaxCode = [
  "window_sum = 0",
  "best = -inf",
  "for right, value in enumerate(nums):",
  "    window_sum += value",
  "    if right >= k - 1:",
  "        best = max(best, window_sum)",
  "        window_sum -= nums[right - k + 1]",
];

const variableSumCode = [
  "left = 0",
  "window_sum = 0",
  "best = inf",
  "for right, value in enumerate(nums):",
  "    window_sum += value",
  "    while window_sum >= target:",
  "        best = min(best, right - left + 1)",
  "        window_sum -= nums[left]; left += 1",
];

const freqCode = [
  "left = 0",
  "freq = Counter()",
  "for right, char in enumerate(s):",
  "    freq[char] += 1",
  "    while window_is_invalid(freq):",
  "        freq[s[left]] -= 1; left += 1",
  "    update_answer(left, right, freq)",
];

const dequeCode = [
  "left = 0",
  "deque = []",
  "for right, value in enumerate(nums):",
  "    while deque and nums[deque[-1]] <= value: deque.pop()",
  "    deque.append(right)",
  "    if deque[0] < left: deque.popleft()",
  "    update_answer(deque[0])",
];

