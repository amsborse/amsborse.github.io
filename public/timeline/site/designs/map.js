    function frame(now) {
      raf = 0;
      if (!tween) return;
      if (!visible) return; // paused offscreen; resumes via whenVisible
      var t = clamp((now - tween.t0) / tween.dur, 0, 1),
        e = tween.ease(t),
        f = tween.from,
        to = tween.to;
      cam = {
        cx: lerp(f.cx, to.cx, e),
        cy: lerp(f.cy, to.cy, e),
        fx: lerp(f.fx, to.fx, e),
        fy: lerp(f.fy, to.fy, e),
        w: Math.exp(lerp(Math.log(f.w), Math.log(to.w), e) + tween.bump * Math.sin(Math.PI * e)),
      };
      drawn = lerp(tween.fromDrawn, tween.toDrawn, e);
      if (!tween.swapped && t >= tween.swapAt) {
        tween.swapped = true;
        showPanel(cur);
      }
      render();
      if (t >= 1) {
        var done = tween;
        tween = null;
        cam = done.to;
        drawn = done.toDrawn;
        render();
        if (!done.swapped) showPanel(cur);
        if (!done.intro) scheduleAdvance();
      } else raf = requestAnimationFrame(frame);
    }
