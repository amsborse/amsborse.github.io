    function flyTo(to, toDrawn, opts) {
      opts = opts || {};
      if (reduced()) {
        tween = null;
        cam = to;
        drawn = toDrawn;
        render();
        stage.animate([{ opacity: 0.3 }, { opacity: 1 }], { duration: 220, easing: "ease-out" });
        if (!opts.keepPanel) showPanel(cur);
        scheduleAdvance();
        return;
      }
      var from = cam,
        fw = Math.max(from.w, to.w),
        bump = 0,
        dist = Math.hypot(to.cx - from.cx, to.cy - from.cy);
      var fit = dist * Math.max(1.5, (dims.W / dims.H) * 0.95) * 1.18; // a view wide enough to hold both ends
      var gm = Math.sqrt(from.w * to.w);
      if (fit > fw * 1.05) bump = Math.log(fit / gm);
      var long = bump > 0;
      tween = {
        t0: performance.now() + (opts.delay || 0),
        dur: opts.dur || (long ? 3600 : 1700),
        from: from,
        to: to,
        fromDrawn: drawn,
        toDrawn: toDrawn,
        bump: bump,
        ease: opts.ease || eio,
        swapAt: long ? 0.62 : 0.5,
        swapped: !!opts.keepPanel,
      };
      kick();
    }

